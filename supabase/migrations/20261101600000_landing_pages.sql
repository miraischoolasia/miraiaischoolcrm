-- Marketing > Landing Page: pages staff build from blocks (the Puck editor) and publish at /p/<slug>, for courses,
-- book sales and events. Each school has its own (its own database).
--
--   * public.landing_pages: one row per page. draft_data is what the editor saves; published_data is what parents
--     see, copied from the draft by publish_landing_page(). data_version is our own block format (migrated in the
--     page code, src/landing/migrations.ts); puck_version is the editor version that saved it.
--   * public.landing_page_versions: a copy of every publish, to go back to an earlier one.
--   * People not signed in never read the tables: get_published_landing_page(slug) gives the published page only,
--     record_landing_view(slug) counts a visit (rate limited like the forms).
--   * bucket landing-images: public pictures for the pages (5 MB, png / jpeg / webp / gif).
--   * the tick 'landing_pages': view = see the list and previews, edit = make, change and publish, delete = delete.
--   * Class Settings > Brand gets the school's public WhatsApp number ('whatsapp'), which the WhatsApp blocks use.

-- ---------------------------------------------------------------------------------------------------------
-- 1. The tick. Patched into the latest valid_account_permissions right after 'quotations', so it does not
--    matter whether 20261101210000_galleries / 20261101400000_data_center_conversions ran before or after.
-- ---------------------------------------------------------------------------------------------------------

create or replace function pg_temp.lp_patch(p_fn regprocedure, p_label text, p_from text, p_to text)
returns void
language plpgsql
as $$
declare
  v_def text := replace(pg_get_functiondef(p_fn), chr(13), '');
begin
  if position(p_to in v_def) > 0 then
    raise notice '%: already there', p_label;
    return;
  end if;
  if position(p_from in v_def) = 0 then
    raise exception '%: the text to change was not found', p_label;
  end if;
  execute replace(v_def, p_from, p_to);
end;
$$;

select pg_temp.lp_patch(
  'public.valid_account_permissions(jsonb)'::regprocedure,
  'valid_account_permissions: landing_pages',
  $x$'progress_cards', 'quotations'$x$,
  $x$'progress_cards', 'quotations', 'landing_pages'$x$
);

-- ---------------------------------------------------------------------------------------------------------
-- 2. The pages
-- ---------------------------------------------------------------------------------------------------------

create table if not exists public.landing_pages (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique
    check (slug ~ '^[a-z0-9][a-z0-9-]{1,59}$'
      and slug not in ('admin', 'api', 'app', 'assets', 'login', 'p', 'preview', 'www')),
  title text not null check (char_length(btrim(title)) between 1 and 120),
  status text not null default 'draft' check (status in ('draft', 'published', 'unpublished')),
  draft_data jsonb not null default '{"root": {"props": {}}, "content": []}'::jsonb
    check (jsonb_typeof(draft_data) = 'object'),
  published_data jsonb check (published_data is null or jsonb_typeof(published_data) = 'object'),
  data_version int not null default 1 check (data_version >= 1),
  published_data_version int,
  puck_version text not null default '',
  -- From the published page's settings (its root props), for the list and the WhatsApp / Facebook preview.
  seo_title text not null default '',
  seo_description text not null default '',
  share_image_url text not null default '',
  views bigint not null default 0,
  published_at timestamptz,
  published_by bigint references public.teachers (id) on delete set null,
  created_by bigint references public.teachers (id) on delete set null default public.current_teacher_id(),
  updated_by bigint references public.teachers (id) on delete set null default public.current_teacher_id(),
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.landing_page_versions (
  id bigint generated by default as identity primary key,
  page_id uuid not null references public.landing_pages (id) on delete cascade,
  data jsonb not null,
  data_version int not null,
  puck_version text not null default '',
  published_at timestamptz not null default timezone('utc', now()),
  published_by bigint references public.teachers (id) on delete set null
);

create index if not exists idx_landing_page_versions_page on public.landing_page_versions (page_id, published_at desc);

-- Who changed it last, and when (a visit counted is not a change).
create or replace function public.landing_pages_touch()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.views is distinct from old.views
     and (to_jsonb(new) - 'views') = (to_jsonb(old) - 'views') then
    return new;
  end if;
  new.updated_at := timezone('utc', now());
  new.updated_by := coalesce(public.current_teacher_id(), new.updated_by);
  return new;
end;
$$;

drop trigger if exists trg_landing_pages_touch on public.landing_pages;
create trigger trg_landing_pages_touch
before update on public.landing_pages
for each row execute function public.landing_pages_touch();

