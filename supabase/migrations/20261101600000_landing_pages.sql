-- ---------------------------------------------------------------------------------------------------------
-- 3. Publishing: the draft becomes what parents see, and a copy is kept.
-- ---------------------------------------------------------------------------------------------------------

create or replace function public.publish_landing_page(p_id uuid)
returns timestamptz
language plpgsql
security definer
set search_path = public
as $$
declare
  v_page public.landing_pages;
  v_root jsonb;
  v_now timestamptz := timezone('utc', now());
  v_by bigint := public.current_teacher_id();
begin
  if not public.has_permission('landing_pages', 'edit') then
    raise exception 'You cannot publish landing pages.';
  end if;
  select * into v_page from public.landing_pages where id = p_id for update;
  if not found then
    raise exception 'This page no longer exists.';
  end if;
  v_root := coalesce(v_page.draft_data -> 'root' -> 'props', '{}'::jsonb);

  update public.landing_pages
  set published_data = v_page.draft_data,
      published_data_version = v_page.data_version,
      status = 'published',
      seo_title = left(coalesce(nullif(btrim(v_root ->> 'shareTitle'), ''), v_page.title), 120),
      seo_description = left(coalesce(btrim(v_root ->> 'shareDescription'), ''), 300),
      share_image_url = left(coalesce(btrim(v_root ->> 'shareImage'), ''), 1000),
      published_at = v_now,
      published_by = v_by
  where id = p_id;

  insert into public.landing_page_versions (page_id, data, data_version, puck_version, published_at, published_by)
  values (p_id, v_page.draft_data, v_page.data_version, v_page.puck_version, v_now, v_by);

  return v_now;
end;
$$;

revoke all on function public.publish_landing_page(uuid) from public, anon;
grant execute on function public.publish_landing_page(uuid) to authenticated;

-- ---------------------------------------------------------------------------------------------------------
-- 4. For everyone: the published page only (never the draft), and counting a visit.
-- ---------------------------------------------------------------------------------------------------------

create or replace function public.get_published_landing_page(p_slug text)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'id', id,
    'slug', slug,
    'title', title,
    'data', published_data,
    'data_version', published_data_version,
    'seo_title', seo_title,
    'seo_description', seo_description,
    'share_image_url', share_image_url
  )
  from public.landing_pages
  where slug = lower(btrim(p_slug)) and status = 'published' and published_data is not null;
$$;

revoke all on function public.get_published_landing_page(text) from public;
grant execute on function public.get_published_landing_page(text) to anon, authenticated;

-- One visit. Quietly not counted when one connection opens the page very often (30 in 10 minutes), or the page
-- gets a flood (5000 in 10 minutes).
create or replace function public.record_landing_view(p_slug text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id uuid;
begin
  select id into v_id from public.landing_pages
  where slug = lower(btrim(p_slug)) and status = 'published';
  if v_id is null then
    return;
  end if;
  begin
    perform public.form_rate_check('landing_view', v_id, 30, 5000);
  exception when others then
    return;
  end;
  perform public.form_rate_record('landing_view', v_id);
  update public.landing_pages set views = views + 1 where id = v_id;
end;
$$;

revoke all on function public.record_landing_view(text) from public;
grant execute on function public.record_landing_view(text) to anon, authenticated;

